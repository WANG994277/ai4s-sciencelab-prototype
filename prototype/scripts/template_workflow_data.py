"""Single content source for leader-template Markdown and editable role diagrams."""
from dataclasses import dataclass, field


@dataclass
class Flow:
    prefix: str
    scene: str
    role: str
    peers: tuple
    height: int
    trigger: str
    goal: str
    scope: str
    nodes: dict = field(default_factory=dict)
    edges: list = field(default_factory=list)

    def add(self, ident, title, page, inp, out, control, qs, mode, y,
            lane=0, branch=False, kind="step", x=None, short=None):
        if x is None:
            x = ([220, 1010, 1440][lane] if not branch else 660)
        width = [380, 340, 360][lane] if not branch else 270
        height = 140
        if kind == "decision":
            x, width, height = 275, 270, 156
        elif kind == "terminal":
            width, height = 340 if not branch else 270, 78
        actor = (self.role, *self.peers)[lane]
        self.nodes[ident] = dict(id=ident,title=title,page=page,inp=inp,out=out,
             control=control,qs=qs,mode=mode,lane=lane,actor=actor,
             x=x,y=y,w=width,h=height,kind=kind,short=short or out)
        return ident

    def port(self, ident, side):
        n=self.nodes[ident]; x,y,w,h=(n[k] for k in ("x","y","w","h"))
        return dict(T=(x+w/2,y),B=(x+w/2,y+h),L=(x,y+h/2),R=(x+w,y+h/2))[side]

    def link(self, source, target, start="B", end="T", via=(), label="", pos=None, dashed=False):
        a,b=self.port(source,start),self.port(target,end)
        if not via and a[0]!=b[0] and a[1]!=b[1]:
            if start in "LR":
                mid=(a[0]+b[0])/2;via=((mid,a[1]),(mid,b[1]))
            else:
                mid=(a[1]+b[1])/2;via=((a[0],mid),(b[0],mid))
        self.edges.append(dict(source=source,target=target,points=[a,*via,b],label=label,pos=pos,dashed=dashed))


